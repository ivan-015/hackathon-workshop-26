// Builds the public slide pages from the decks exported out of Claude.
//
// Each deck in slides/<lang>/ is deck.json (title, order, fonts) plus one
// <section> per slide in slides/<lang>/slides/<id>.html. This script stitches
// them into public/slides/<lang>/index.html, drops the speaker notes, and
// points the deck's /_blob/ images at files in public/slides/img/.
//
//   npm run slides

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;

const DECKS = [
  { lang: 'en', label: 'English', other: { lang: 'es', label: 'Español' }, back: 'All links', hint: 'Turn your phone sideways for bigger slides. Swipe or tap to move.' },
  { lang: 'es', label: 'Español', other: { lang: 'en', label: 'English' }, back: 'Todos los links', hint: 'Gira tu teléfono para ver las diapositivas más grandes. Desliza o toca para avanzar.' },
];

// Both decks share the same two screenshots, uploaded once per deck.
const BLOBS = {
  '4997a23cf03db4881931146824e0ddb7': '/slides/img/links-before.png',
  '03356b7e79dc37c942a4e2e19b9edde5': '/slides/img/links-before.png',
  'c8e80f9fd6d5debd89a6612b579ddf65': '/slides/img/links-after.webp',
  '7377505fc9606f21869cb9e18dd1728e': '/slides/img/links-after.webp',
};

const SLIDE_ID = /^[A-Za-z0-9_-]{1,64}$/;
const FONT_HREF = /^https:\/\/fonts\.googleapis\.com\/css2\?/;

const escapeHtml = (s) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);

function prepareSlide(html, id, file) {
  if (!new RegExp(`^\\s*<section id="${id}"`).test(html)) {
    throw new Error(`${file}: expected one <section id="${id}">`);
  }
  const withImages = html.replace(/\/_blob\/([0-9a-f]+)/g, (_, blob) => {
    if (!BLOBS[blob]) throw new Error(`${file}: no local file for image /_blob/${blob}`);
    return BLOBS[blob];
  });
  return withImages.replace(/\s*<aside>[\s\S]*?<\/aside>/, '').trim();
}

async function readDeck(lang) {
  const dir = join(ROOT, 'slides', lang);
  const deck = JSON.parse(await readFile(join(dir, 'deck.json'), 'utf8'));
  if (!Array.isArray(deck.order) || deck.order.length === 0) throw new Error(`slides/${lang}/deck.json has no slides`);
  const bad = deck.order.find((id) => !SLIDE_ID.test(id));
  if (bad) throw new Error(`slides/${lang}/deck.json: invalid slide id "${bad}"`);

  const slides = await Promise.all(deck.order.map(async (id) => {
    const file = `slides/${lang}/slides/${id}.html`;
    return prepareSlide(await readFile(join(ROOT, file), 'utf8'), id, file);
  }));
  const fonts = Object.values(deck.faces ?? {}).map((f) => f.href).filter((href) => FONT_HREF.test(href ?? ''));
  return { title: deck.title, slides, fonts };
}

function renderPage({ lang, label, other, back, hint },{ title, slides, fonts }) {
  const fontLinks = fonts.map((href) => `  <link href="${escapeHtml(href)}" rel="stylesheet">`).join('\n');
  return `<!doctype html>
<!-- Generated by scripts/build-slides.mjs from slides/${lang}/. Edit the deck there, then run npm run slides. -->
<html lang="${lang}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <meta name="theme-color" content="#0d141c">
  <title>${escapeHtml(title)} · Slides</title>
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
${fontLinks}
  <link rel="stylesheet" href="/slides/viewer.css">
</head>
<body>
  <header class="bar">
    <a href="/">&larr; ${escapeHtml(back)}</a>
    <nav class="langs" aria-label="Language">
      <span aria-current="page">${escapeHtml(label)}</span>
      <a class="lang-switch" href="/slides/${other.lang}/" hreflang="${other.lang}" lang="${other.lang}">${escapeHtml(other.label)}</a>
    </nav>
  </header>
  <main class="viewport" aria-roledescription="carousel" aria-label="${escapeHtml(title)}">
    <div class="stage">
${slides.join('\n')}
    </div>
    <p class="hint">${escapeHtml(hint)}</p>
  </main>
  <footer class="bar">
    <button type="button" class="prev" aria-label="Previous slide">&larr;</button>
    <span class="count" aria-live="polite"></span>
    <button type="button" class="next" aria-label="Next slide">&rarr;</button>
  </footer>
  <script src="/slides/viewer.js"></script>
</body>
</html>
`;
}

for (const meta of DECKS) {
  const deck = await readDeck(meta.lang);
  const outDir = join(ROOT, 'public', 'slides', meta.lang);
  await mkdir(outDir, { recursive: true });
  await writeFile(join(outDir, 'index.html'), renderPage(meta, deck));
  console.log(`public/slides/${meta.lang}/index.html  ${deck.slides.length} slides  "${deck.title}"`);
}
